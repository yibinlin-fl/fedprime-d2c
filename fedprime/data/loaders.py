@dataclass(frozen=True)
class DatasetStats:
    mean: list[float]
    std: list[float]


class GaussianBlur:
    def __init__(self, sigma=(0.1, 2.0)):
        self.sigma = sigma

    def __call__(self, x):
        sigma = random.uniform(self.sigma[0], self.sigma[1])
        return x.filter(ImageFilter.GaussianBlur(radius=sigma))


class TwoViewTransform:
    def __init__(self, transform, weak_transform):
        self.transform = transform
        self.weak_transform = weak_transform

    def __call__(self, x):
        return self.transform(x), self.weak_transform(x)


class CorruptionSkewClientDataset(data.Dataset):
    """Client-local CIFAR-10 dataset generated by the corruption-skew protocol."""

    def __init__(
        self,
        root: str | Path,
        client_id: int | None = None,
        train: bool = True,
        transform=None,
        return_corruption: bool = False,
        evaluation_split: str = "test_balanced",
    ):
        self.root = Path(root)
        self.client_id = client_id
        self.train = train
        self.transform = transform
        self.return_corruption = return_corruption
        self.evaluation_split = str(evaluation_split)
        metadata_path = self.root / "metadata.json"
        self.metadata = (
            json.loads(metadata_path.read_text(encoding="utf-8"))
            if metadata_path.is_file()
            else {}
        )
        self.corruption_names = self._load_corruption_names()
        self.corruption_splits = {
            str(name): str(split)
            for name, split in self.metadata.get("operator_splits", {}).items()
        }
        if train:
            if client_id is None:
                raise ValueError("client_id is required for corruption-skew training data.")
            data_dir = self.root / f"client_{client_id}"
            self.data = np.load(data_dir / "train_images.npy")
            self.targets = np.load(data_dir / "train_labels.npy")
            self.corruption_ids = np.load(data_dir / "train_corruption_ids.npy")
        else:
            data_dir = self.root / self.evaluation_split
            self.data = np.load(data_dir / "test_images.npy")
            self.targets = np.load(data_dir / "test_labels.npy")
            self.corruption_ids = np.load(data_dir / "test_corruption_ids.npy")

    def _load_corruption_names(self) -> dict[int, str]:
        raw = self.metadata.get("operator_to_id")
        if isinstance(raw, dict):
            return {int(value): str(name) for name, value in raw.items()}
        raw = self.metadata.get("group_to_id")
        if isinstance(raw, dict):
            return {int(value): str(name) for name, value in raw.items()}
        return {int(idx): str(name) for idx, name in ID_TO_GROUP.items()}

    def __len__(self) -> int:
        return int(self.targets.shape[0])

    def __getitem__(self, index: int):
        image = self.data[index]
        label = int(self.targets[index])
        corruption_id = int(self.corruption_ids[index])
        if self.transform is not None:
            image = self.transform(image)
        if self.return_corruption:
            return image, label, corruption_id
        return image, label


class NumpyImageClassificationDataset(data.Dataset):
    """Small fallback dataset for CIFAR tarballs when extracted files are unavailable."""

    def __init__(self, images: np.ndarray, labels: np.ndarray, transform=None):
        self.images = np.asarray(images, dtype=np.uint8)
        self.labels = np.asarray(labels, dtype=np.int64)
        self.transform = transform

    def __len__(self) -> int:
        return int(self.labels.shape[0])

    def __getitem__(self, index: int):
        image = Image.fromarray(self.images[index])
        if self.transform is not None:
            image = self.transform(image)
        return image, int(self.labels[index])


