def partition_private_data(
    labels: np.ndarray,
    num_clients: int,
    num_classes: int,
    partition: str,
    dirichlet_alpha: float,
    max_samples_per_client: int | None = None,
    partition_indices_path: str | Path | None = None,
    partition_seed: int | None = None,
) -> dict[int, list[int]]:
    metadata = {
        "num_labels": int(len(labels)),
        "num_clients": int(num_clients),
        "num_classes": int(num_classes),
        "partition": str(partition),
        "dirichlet_alpha": float(dirichlet_alpha),
        "max_samples_per_client": (
            None if max_samples_per_client is None else int(max_samples_per_client)
        ),
    }
    if partition_indices_path:
        path = Path(partition_indices_path)
        if path.exists():
            return _load_partition_indices(path, metadata)

    rng = np.random.default_rng(partition_seed)
    if partition == "iid":
        mapping = _iid_partition_indices(len(labels), num_clients, rng)
    elif partition == "dirichlet":
        min_require_size = 10
        if max_samples_per_client is not None:
            min_require_size = int(max_samples_per_client)
        mapping = _dirichlet_partition_indices(
            labels=labels,
            num_classes=num_classes,
            num_clients=num_clients,
            alpha=dirichlet_alpha,
            rng=rng,
            min_require_size=min_require_size,
        )
    else:
        raise ValueError(f"Unknown partition: {partition}")

    if max_samples_per_client is not None:
        mapping = {
            client_id: list(indices[:max_samples_per_client])
            for client_id, indices in mapping.items()
        }
    if partition_indices_path:
        _save_partition_indices(Path(partition_indices_path), mapping, metadata)
    return mapping


def _iid_partition_indices(
    num_labels: int,
    num_clients: int,
    rng: np.random.Generator,
) -> dict[int, list[int]]:
    indices = rng.permutation(num_labels)
    splits = np.array_split(indices, num_clients)
    return {client_id: split.astype(np.int64).tolist() for client_id, split in enumerate(splits)}


def _dirichlet_partition_indices(
    labels: np.ndarray,
    num_classes: int,
    num_clients: int,
    alpha: float,
    rng: np.random.Generator,
    min_require_size: int = 10,
) -> dict[int, list[int]]:
    labels = np.asarray(labels)
    num_labels = labels.shape[0]
    min_size = 0
    idx_batch: list[list[int]] = [[] for _ in range(num_clients)]

    while min_size < min_require_size:
        idx_batch = [[] for _ in range(num_clients)]
        for class_id in range(num_classes):
            class_indices = np.where(labels == class_id)[0]
            rng.shuffle(class_indices)
            proportions = rng.dirichlet(np.repeat(float(alpha), num_clients))
            proportions = np.array(
                [
                    proportion * (len(client_indices) < num_labels / num_clients)
                    for proportion, client_indices in zip(proportions, idx_batch)
                ],
                dtype=np.float64,
            )
            proportions = proportions / proportions.sum()
            split_points = (np.cumsum(proportions) * len(class_indices)).astype(int)[:-1]
            for client_indices, split in zip(idx_batch, np.split(class_indices, split_points)):
                client_indices.extend(split.astype(np.int64).tolist())
        min_size = min(len(client_indices) for client_indices in idx_batch)

    mapping = {}
    for client_id, client_indices in enumerate(idx_batch):
        shuffled = np.asarray(client_indices, dtype=np.int64)
        rng.shuffle(shuffled)
        mapping[client_id] = shuffled.tolist()
    return mapping


def _load_partition_indices(path: Path, expected: dict[str, object]) -> dict[int, list[int]]:
    with np.load(path, allow_pickle=False) as data:
        if "__meta__" not in data:
            raise ValueError(f"Partition file {path} has no metadata.")
        metadata = json.loads(str(data["__meta__"].item()))
        for key, value in expected.items():
            if metadata.get(key) != value:
                raise ValueError(
                    f"Partition file {path} metadata mismatch for {key}: "
                    f"expected {value!r}, got {metadata.get(key)!r}."
                )
        mapping = {}
        for client_id in range(int(expected["num_clients"])):
            key = f"client_{client_id}"
            if key not in data:
                raise ValueError(f"Partition file {path} is missing {key}.")
            mapping[client_id] = data[key].astype(np.int64).tolist()
    return mapping


def _save_partition_indices(path: Path, mapping: dict[int, list[int]], metadata: dict[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    arrays = {
        f"client_{client_id}": np.asarray(indices, dtype=np.int64)
        for client_id, indices in sorted(mapping.items())
    }
    np.savez_compressed(
        path,
        __meta__=json.dumps(metadata, ensure_ascii=False),
        **arrays,
    )


