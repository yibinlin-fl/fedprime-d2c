def dataset_stats(name: str) -> DatasetStats:
    if name.lower() == "cifar10":
        return DatasetStats(CIFAR10_MEAN, CIFAR10_STD)
    if name.lower() == "cifar100":
        return DatasetStats(CIFAR100_MEAN, CIFAR100_STD)
    raise ValueError(f"Unsupported dataset stats: {name}")


def normalize_batch(images: torch.Tensor, stats: DatasetStats) -> torch.Tensor:
    mean = torch.tensor(stats.mean, device=images.device).view(1, -1, 1, 1)
    std = torch.tensor(stats.std, device=images.device).view(1, -1, 1, 1)
    return (images - mean) / std


def _private_train_transform(raw_for_prime: bool):
    if raw_for_prime:
        return T.Compose([
            T.ToTensor(),
            T.Lambda(lambda x: F.pad(
                Variable(x.unsqueeze(0), requires_grad=False),
                (4, 4, 4, 4),
                mode="reflect",
            ).data.squeeze()),
            T.ToPILImage(),
            T.ColorJitter(),
            T.RandomCrop(32),
            T.RandomHorizontalFlip(),
            T.ToTensor(),
        ])
    return T.Compose([
        T.ToTensor(),
        T.Lambda(lambda x: F.pad(
            Variable(x.unsqueeze(0), requires_grad=False),
            (4, 4, 4, 4),
            mode="reflect",
        ).data.squeeze()),
        T.ToPILImage(),
        T.ColorJitter(),
        T.RandomCrop(32),
        T.RandomHorizontalFlip(),
        T.ToTensor(),
        T.Normalize(CIFAR10_MEAN, CIFAR10_STD),
    ])


def _prime_dcl_train_transform():
    base = T.Compose([
        T.ToTensor(),
        T.Lambda(lambda x: F.pad(
            Variable(x.unsqueeze(0), requires_grad=False),
            (4, 4, 4, 4),
            mode="reflect",
        ).data.squeeze()),
        T.ToPILImage(),
        T.ColorJitter(),
        T.RandomCrop(32),
        T.RandomHorizontalFlip(),
        T.ToTensor(),
    ])
    weak = T.Compose([
        T.ToTensor(),
        T.Lambda(lambda x: F.pad(
            Variable(x.unsqueeze(0), requires_grad=False),
            (4, 4, 4, 4),
            mode="reflect",
        ).data.squeeze()),
        T.ToPILImage(),
        T.RandomResizedCrop(size=32, scale=(0.2, 1.0)),
        T.RandomApply([T.ColorJitter(0.4, 0.4, 0.4, 0.1)], p=0.8),
        T.RandomGrayscale(p=0.2),
        T.RandomApply([GaussianBlur()], p=0.5),
        T.RandomHorizontalFlip(),
        T.ToTensor(),
    ])
    return TwoViewTransform(base, weak)


def _rahfl_augmix_view_transforms(dataset_name: str = "cifar10"):
    stats = dataset_stats(dataset_name)
    base = T.Compose([
        T.ToTensor(),
        T.Lambda(lambda x: F.pad(
            Variable(x.unsqueeze(0), requires_grad=False),
            (4, 4, 4, 4),
            mode="reflect",
        ).data.squeeze()),
        T.ToPILImage(),
        T.ColorJitter(),
        T.RandomCrop(32),
        T.RandomHorizontalFlip(),
    ])
    weak = T.Compose([
        T.ToTensor(),
        T.Lambda(lambda x: F.pad(
            Variable(x.unsqueeze(0), requires_grad=False),
            (4, 4, 4, 4),
            mode="reflect",
        ).data.squeeze()),
        T.ToPILImage(),
        T.RandomResizedCrop(size=32, scale=(0.2, 1.0)),
        T.RandomApply([T.ColorJitter(0.4, 0.4, 0.4, 0.1)], p=0.8),
        T.RandomGrayscale(p=0.2),
        T.RandomApply([GaussianBlur()], p=0.5),
        T.RandomHorizontalFlip(),
    ])
    preprocess = T.Compose([
        T.ToTensor(),
        T.Normalize(stats.mean, stats.std),
    ])
    return base, weak, preprocess


def _private_test_transform(dataset_name: str = "cifar10"):
    stats = dataset_stats(dataset_name)
    return T.Compose([
        T.ToTensor(),
        T.Normalize(stats.mean, stats.std),
    ])


def _prepared_private_dataset_name(root: str | Path) -> str:
    metadata_path = Path(root) / "metadata.json"
    if not metadata_path.is_file():
        return "cifar10"
    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    explicit = metadata.get("private_dataset")
    if explicit:
        return str(explicit).lower()
    return "cifar100" if "cifar100" in str(metadata.get("dataset", "")).lower() else "cifar10"


